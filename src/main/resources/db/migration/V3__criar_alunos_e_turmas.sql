CREATE TABLE alunos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(150) NOT NULL CHECK (length(trim(nome)) BETWEEN 3 AND 150),
 cpf varchar(11) NOT NULL CHECK (cpf ~ '^[0-9]{11}$'),
 data_nascimento date NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT uk_alunos_cpf UNIQUE(cpf)
);
CREATE INDEX ix_alunos_nome ON alunos(lower(nome));

CREATE TABLE turmas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_professor bigint NOT NULL CONSTRAINT fk_turma_professor REFERENCES professores(id),
 id_unidade bigint NOT NULL CONSTRAINT fk_turma_unidade REFERENCES unidades(id),
 nome varchar(120) NOT NULL CHECK (length(trim(nome)) BETWEEN 3 AND 120),
 status varchar(20) NOT NULL DEFAULT 'ATIVA' CHECK (status IN ('ATIVA','INATIVA','CONCLUIDA')),
 carga_horaria integer NOT NULL CHECK (carga_horaria BETWEEN 1 AND 9999),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_turmas_nome ON turmas(id_unidade,lower(nome));
CREATE INDEX ix_turmas_professor_status ON turmas(id_professor,status);
