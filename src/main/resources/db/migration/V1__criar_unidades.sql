CREATE TABLE unidades (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(120) NOT NULL CHECK (length(trim(nome)) BETWEEN 3 AND 120),
    sigla varchar(10) NOT NULL CHECK (sigla ~ '^[A-Z0-9]{2,10}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_unidades_sigla UNIQUE (sigla)
);
CREATE UNIQUE INDEX uk_unidades_nome ON unidades(lower(nome));
